using System;
using UnityEngine;
using UnityEngine.SceneManagement;
using Unity.Hare.Content;
using Unity.Hare.Input;
using Unity.Hare.Rendering;
using Unity.Hare.Session;

namespace Unity.Hare.Flow
{
    /// <summary>
    /// Plays Core's <see cref="RoomFlow"/> (U.HARE-T50): the one object that owns the flow, created by the bootstrap
    /// scene (Main.unity, which holds nothing else) and kept across room loads. Each frame it steps the current room
    /// at its room_speed (the obj_fade_* Step event), sends Esc and F1 as <see cref="PressEscape"/> and
    /// <see cref="PressFullscreen"/>, and plays what comes back: a <see cref="RoomChanged"/> loads that room's scene
    /// (named after the GML room, generated by ProjectSetup), <see cref="FullscreenToggled"/> flips
    /// <see cref="Screen.fullScreen"/>, and the fade's opacity is drawn black on the room camera's
    /// <see cref="ScreenOverlayLayer"/> (obj_fade_*'s spr_black stretched over the room). It never decides a rule
    /// itself; menus and controllers in the rooms ask it to <see cref="Execute"/> commands.
    ///
    /// A room scene that loads without the flow sending it there (obj_player's death reloading the room, or a room
    /// scene opened on its own in the Editor) is reported to the flow as <see cref="EnterRoom"/>. A scene that is not
    /// a room (the online scene) leaves the director idle until a room loads again.
    /// </summary>
    [DisallowMultipleComponent]
    public sealed class RoomFlowDirector : MonoBehaviour
    {
        /// <summary>The bootstrap scene's director sends the game to the table's first room on Start.</summary>
        [SerializeField] bool enterFirstRoom = true;

        /// <summary>The seat local play acts for (the room flow is not per player; the id is who asked).</summary>
        static readonly PlayerId LocalSeat = new PlayerId(1);

        HareControls controls;
        ScreenOverlayLayer overlay;
        string pendingScene;
        double stepAccumulator;
        bool warnedLevelAdvance;
        int roomChangedFrame = -1;

        /// <summary>The director the game is running under; null outside the local game.</summary>
        public static RoomFlowDirector Active { get; private set; }

        /// <summary>The flow this director plays.</summary>
        public RoomFlow Flow { get; private set; }

        /// <summary>
        /// globals.gml's state for this game (LIVES, COINS, the score...): the one session the local game's authority
        /// holds, kept across room loads with the flow. <see cref="RestartGame"/> replaces it (game_restart).
        /// </summary>
        public GameSession Session { get; private set; }

        /// <summary>
        /// The campaign save (U.HARE-T65, docs/BIBLE.md V50): the map missions won (V42), the garage's pips (V49), the
        /// COINS carried, the level the campaign run reached and the best scores, read from the profile's
        /// <c>campaign.json</c> (<see cref="CampaignStore"/>) at start and again whenever the campaign is chosen, and
        /// saved at its checkpoints (<see cref="PlaySession"/>). It outlives game_restart, as a save does.
        /// </summary>
        public CampaignProgress Campaign { get; private set; }

        /// <summary>Every event the session raises through <see cref="ExecuteSession"/> or <see cref="PlaySession"/>.</summary>
        public event Action<SessionEvent> SessionEventPlayed;

        /// <summary>game_restart ran: a new <see cref="Session"/> and the game back at the table's first room.</summary>
        public event Action GameRestarted;

        /// <summary>False while a scene that is not a room (the online scene) is loaded.</summary>
        public bool InRoom { get; private set; }

        /// <summary>Every event the flow raises, after the director has played it.</summary>
        public event Action<FlowEvent> EventPlayed;

        /// <summary>
        /// One step of the current room at its room_speed, after the flow's own (the obj_fade_* Step): a room's own
        /// objects (obj_startup, U.HARE-T51) step their Core state on this clock, so a room runs one clock.
        /// </summary>
        public event Action<RoomId> RoomStepped;

        /// <summary>
        /// obj_fade_game reached black: <c>current_level += 1; setup_level();</c>. The level setup (U.HARE-T57)
        /// subscribes; until it does, the play room stays black, as it would in the original without setup_level.
        /// </summary>
        public event Action LevelAdvance;

        /// <summary>Whether <see cref="Screen.fullScreen"/> is set; a seam so tests can watch F1 without a window.</summary>
        public Func<bool> GetFullscreen = () => Screen.fullScreen;
        public Action<bool> SetFullscreen = value => Screen.fullScreen = value;

        /// <summary>
        /// Loads a room's scene; a seam so tests can watch the flow without leaving their own scene. Defaults to
        /// <see cref="SceneManager.LoadScene(string, LoadSceneMode)"/>, single mode, by the room's GML name.
        /// </summary>
        public Action<string> LoadRoomScene = name => SceneManager.LoadScene(name, LoadSceneMode.Single);

        void Awake()
        {
            // Loading the bootstrap again (Play solo from the online scene) starts the game over under this director.
            if (Active != null && Active != this) Destroy(Active.gameObject);
            Active = this;
            DontDestroyOnLoad(gameObject);
            Flow = new RoomFlow(GameContent.Current);
            Session = NewSession();
            Campaign = CampaignStore.Load();
            controls = new HareControls();
            controls.Meta.Menu.Enable();
            controls.Meta.Fullscreen.Enable();
            SceneManager.sceneLoaded += OnSceneLoaded;
        }

        void Start()
        {
            if (enterFirstRoom && Flow.Current == null) Execute(new GoToRoom(LocalSeat, Flow.Table.FirstRoom));
        }

        void OnDestroy()
        {
            SceneManager.sceneLoaded -= OnSceneLoaded;
            if (Active == this)
            {
                Active = null;
                SystemCursor.Restore(); // the game's rooms are gone: the system cursor comes back as it was
            }
            if (controls != null)
            {
                controls.Disable();
                controls.Dispose();
            }
        }

        /// <summary>Runs <paramref name="command"/> on the flow and plays every event it raised.</summary>
        public FlowResult Execute(FlowCommand command)
        {
            var result = Flow.Execute(command);
            foreach (var e in result.Events) Play(e);
            return result;
        }

        /// <summary>Runs <paramref name="command"/> on the session and plays every event it raised.</summary>
        public SessionResult ExecuteSession(SessionCommand command)
        {
            var result = Session.Execute(command);
            PlaySession(result);
            return result;
        }

        /// <summary>
        /// Plays what a session command run elsewhere (a ship spending a life) raised, and keeps the campaign save
        /// (U.HARE-T65, docs/BIBLE.md V50) in step: a campaign chosen reads the save again and puts it on the session
        /// (<see cref="RestoreCampaign"/>); a mission won, a campaign level finished (its best score, the COINS carried)
        /// and a campaign run moving on (the scenario and level reached) each write it once, never on every coin.
        /// </summary>
        public void PlaySession(SessionResult result)
        {
            if (result.Events == null) return;
            bool changed = false, restore = false;
            foreach (var e in result.Events)
            {
                if (Campaign != null) changed |= RecordCampaign(e, ref restore);
                SessionEventPlayed?.Invoke(e);
            }
            if (changed) CampaignStore.Save(Campaign);
            if (restore) ExecuteSession(new RestoreCampaign(LocalSeat, Campaign));
        }

        /// <summary>What <paramref name="e"/> changes in <see cref="Campaign"/>; true when the save needs writing.</summary>
        bool RecordCampaign(SessionEvent e, ref bool restore)
        {
            switch (e)
            {
                case GameModeChosen chosen when chosen.Mode == GameMode.Campaign:
                    if (!campaignInjected) Campaign = CampaignStore.Load();
                    restore = true;
                    return false;
                case MissionWon won:
                    return Campaign.RecordWin(won.Scenario);
                case LevelCompleted done when Session.Mode == GameMode.Campaign:
                    bool best = Campaign.RecordScore(Math.Max(1, done.Level), Session.Score);
                    return Campaign.RecordCoins(Session.Coins) | best | RecordReached();
                case LevelAdvanced _ when Session.Mode == GameMode.Campaign:
                case ScenarioChanged _ when Session.Mode == GameMode.Campaign:
                    return Campaign.RecordCoins(Session.Coins) | RecordReached();
                default:
                    return false;
            }
        }

        /// <summary>The campaign run's scenario and level (a map mission's are its own, not the run's).</summary>
        bool RecordReached()
        {
            if (Session.MissionLevel > 0 || Session.Level < 1 || Session.Scenario == 0 || Session.Scenario < CampaignProgress.NoScenario) return false;
            return Campaign.RecordReached(Session.Scenario, Session.Level);
        }

        /// <summary>
        /// Puts <paramref name="progress"/> in place of the loaded campaign (tests): it stays in use, rather than the save
        /// being read again, when the campaign is chosen.
        /// </summary>
        public void UseCampaign(CampaignProgress progress)
        {
            Campaign = progress ?? new CampaignProgress();
            campaignInjected = true;
        }

        bool campaignInjected;

        /// <summary>
        /// The garage's SKILLPOINTS left (U.HARE-T24, docs/BIBLE.md V49, D27): globals.gml's starting 5, plus a point for
        /// each map mission's first win, less the pips bought, all read from <see cref="Campaign"/>.
        /// </summary>
        public int SkillPoints => Campaign.SkillPoints(Session.Tuning.StartingSkillPoints, GameContent.Current.Upgrades);

        /// <summary>What the garage's bought pips do to the local ship's weapons (fitted as it enters a play room).</summary>
        public Weapons.ShipUpgrades ShipUpgrades => GameContent.Current.Upgrades.EffectsOf(Campaign.Upgrades);

        /// <summary>Writes <see cref="Campaign"/> to <c>campaign.json</c> (a pip bought); false when it could not be written.</summary>
        public bool SaveCampaign() => CampaignStore.Save(Campaign);

        /// <summary>
        /// GML game_restart: the game starts over as if just launched. globals.gml runs again (a new
        /// <see cref="GameSession"/>, every global back at its start) and the game goes to the table's first room.
        /// </summary>
        public void RestartGame()
        {
            Session = NewSession();
            SessionEventPlayed?.Invoke(new SessionReset());
            GameRestarted?.Invoke();
            Execute(new GoToRoom(LocalSeat, Flow.Table.FirstRoom));
        }

        /// <summary>globals.gml's new session, with the player's saved master volume and units on it (U.HARE-T60).</summary>
        static GameSession NewSession()
        {
            var session = new GameSession(GameContent.Current);
            SessionSettings.Seed(session, LocalSeat);
            return session;
        }

        /// <summary>A command for the local seat: <c>Execute(new FadeToRoom(Seat, ...))</c>.</summary>
        public static PlayerId Seat => LocalSeat;

        void Update()
        {
            if (!InRoom || Flow.Current == null) return;

            // A key press belongs to the room it was pressed in: when a room's own object already left on it this
            // frame (obj_startup's any key, F1 among them), the next room does not answer it too, as room_goto only
            // takes effect once GameMaker's step is over.
            if (Time.frameCount != roomChangedFrame)
            {
                if (controls.Meta.Menu.WasPressedThisFrame()) Execute(new PressEscape(LocalSeat));
                if (controls.Meta.Fullscreen.WasPressedThisFrame()) Execute(new PressFullscreen(LocalSeat));
            }
            StepFor(Time.unscaledDeltaTime);
        }

        /// <summary>
        /// Runs the room steps <paramref name="seconds"/> of real time are worth at the room's room_speed, at most
        /// <see cref="RoomTable.MaxStepsPerFrame"/> of them; a room change ends the frame's steps (the new room's
        /// first step is next frame, as GameMaker's room_goto takes effect at the end of the step).
        /// </summary>
        public void StepFor(float seconds)
        {
            if (Flow.Current == null) return;
            stepAccumulator += seconds * Flow.StepsPerSecond;
            int steps = (int)Math.Floor(stepAccumulator);
            stepAccumulator -= steps;
            steps = Math.Min(steps, Flow.Table.MaxStepsPerFrame);

            var room = Flow.Current;
            for (int i = 0; i < steps && Flow.Current == room; i++)
            {
                Execute(new StepRoom(LocalSeat));
                if (Flow.Current == room) RoomStepped?.Invoke(room.Value);
            }
        }

        void LateUpdate()
        {
            if (overlay == null) return;
            overlay.Color = new Color(0f, 0f, 0f, InRoom ? Flow.FadeOpacity : 0f);
        }

        void Play(FlowEvent e)
        {
            switch (e)
            {
                case RoomChanged changed:
                    stepAccumulator = 0d;
                    roomChangedFrame = Time.frameCount;
                    pendingScene = RoomList.GmlName(changed.To);
                    InRoom = true;
                    LoadRoomScene(pendingScene);
                    break;
                case RoomEntered _:
                    stepAccumulator = 0d;
                    break;
                case FullscreenToggled _:
                    SetFullscreen(!GetFullscreen()); // window_set_fullscreen(!window_get_fullscreen())
                    break;
                case LevelAdvanceRequested _:
                    if (LevelAdvance != null) LevelAdvance();
                    else if (!warnedLevelAdvance)
                    {
                        warnedLevelAdvance = true;
                        Debug.LogWarning("[Unity.Hare] obj_fade_game reached black, but nothing sets up the next level yet (U.HARE-T57).");
                    }
                    break;
            }
            EventPlayed?.Invoke(e);
        }

        void OnSceneLoaded(Scene scene, LoadSceneMode mode)
        {
            if (!RoomList.TryParse(scene.name, out var room))
            {
                if (mode == LoadSceneMode.Single)
                {
                    InRoom = false; // the online scene, or another non-room scene
                    SystemCursor.Restore();
                }
                return;
            }

            InRoom = true;
            if (pendingScene == scene.name) pendingScene = null;
            else Execute(new EnterRoom(LocalSeat, room)); // room_restart, or a room opened outside the flow
            SetUpRoomScene(scene, room);
        }

        /// <summary>
        /// What every room scene gets as it comes up: the camera's screen overlay the fade draws on, HARE.gmx's
        /// option_showcursor (the system cursor hidden), and the obj_mouse its controller creates (U.HARE-T61): the map's and
        /// upgrade room's spr_pointer and the play rooms' reticle. obj_title, obj_map and obj_upgrade make their own
        /// (U.HARE-T26's TitleRoom, U.HARE-T19's MapRoom and U.HARE-T64's UpgradeRoom, during the scene's Awake, so it is
        /// already there); any other room's is made here.
        /// </summary>
        void SetUpRoomScene(Scene scene, RoomId room)
        {
            overlay = FindOverlay(scene);
            SystemCursor.ApplyForRoom(GameContent.Current.Mouse.ShowSystemCursor);
            if (MouseView.Active == null || MouseView.Active.gameObject.scene != scene) MouseView.Create(room, scene);
        }

        /// <summary>The room camera's screen overlay, which the fade draws on.</summary>
        static ScreenOverlayLayer FindOverlay(Scene scene)
        {
            foreach (var root in scene.GetRootGameObjects())
            {
                var found = root.GetComponentInChildren<ScreenOverlayLayer>(true);
                if (found != null) return found;
            }
            return null;
        }

        /// <summary>
        /// Pressing Play on a room scene in the Editor (no bootstrap) still runs the flow: a director is made for it
        /// and told the room came up on its own.
        /// </summary>
        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]
        static void EnsureForRoomScene()
        {
            if (Active != null) return;
            var scene = SceneManager.GetActiveScene();
            if (!RoomList.TryParse(scene.name, out var room)) return;
            var go = new GameObject("RoomFlow");
            var director = go.AddComponent<RoomFlowDirector>();
            director.enterFirstRoom = false;
            director.InRoom = true;
            director.Execute(new EnterRoom(LocalSeat, room));
            director.SetUpRoomScene(scene, room);
        }

        /// <summary>Builds the bootstrap's director (ProjectSetup composes Main.unity from this).</summary>
        public static RoomFlowDirector Create(bool enterFirstRoom)
        {
            var go = new GameObject("RoomFlow");
            var director = go.AddComponent<RoomFlowDirector>();
            director.enterFirstRoom = enterFirstRoom;
            return director;
        }
    }
}
